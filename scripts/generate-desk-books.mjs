// Generates plugins/coa-desk/hooks/books.ts from the server's book table, so
// the desk's reference parser accepts exactly the names the server resolves.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SERVER_BOOKS = path.join(ROOT, "server/src/db/books.ts");
export const BOOKS_PATH = path.join(ROOT, "plugins/coa-desk/hooks/books.ts");

export async function generateDeskBooks() {
  const source = await fs.readFile(SERVER_BOOKS, "utf8");
  const entry = /^\s+'([^']+)': \{ canonical: '([^']+)', displayName: '([^']+)', testament: '(ot|nt)'/gm;
  const books = new Map();
  for (const [, alias, canonical, name, testament] of source.matchAll(entry)) {
    if (!books.has(canonical)) books.set(canonical, { name, testament, aliases: [] });
    books.get(canonical).aliases.push(alias);
  }
  const ordered = [...books.values()].sort(
    (a, b) => (a.testament === b.testament ? 0 : a.testament === "ot" ? -1 : 1),
  );
  const rows = ordered.map(
    (book) => `  { name: ${JSON.stringify(book.name)}, testament: ${JSON.stringify(book.testament)}, aliases: ${JSON.stringify(book.aliases)} },`,
  );
  return [
    "// Generated by scripts/generate-desk-books.mjs from server/src/db/books.ts. Do not edit directly.",
    "// Aliases are lower case with spaces, hyphens and underscores removed.",
    "export const BOOKS = [",
    ...rows,
    "]",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await fs.writeFile(BOOKS_PATH, await generateDeskBooks());
}
